//! Flamework's transformer as a compiled-in rbxts-rs plugin (DESIGN §10).
//!
//! F0, the foundation that needs no compiler:
//! - [`config`]: `flamework.config.json` (find, read, substitute the environment, coerce, validate) and the tsconfig
//!   entry check, with the TS transformer's error texts;
//! - [`env`]: `.env` / `.env.local` loading and the `${NAME:-fallback}` substitution;
//! - [`build_info`]: `flamework.build` read and write (byte for byte), package build-info discovery, the version
//!   checks;
//! - [`ids`]: the `full` / `short` / `tiny` / `obfuscated` id rules, late-bound in program order (§10.4);
//! - the byte-exact libraries (§10.5): [`hashids`], [`uuid`], [`sha`], [`glob`], plus [`json`] (JavaScript's
//!   `JSON.parse` / `JSON.stringify` with its property order) and [`jsonc`] (TypeScript's JSON-with-comments
//!   reader, as `ts.parseConfigFileTextToJson` reads a config file).
//!
//! Every library has a table-driven parity test against the node library (`tests/data`, generated by
//! `tests/data/gen/generate.cjs`).
//!
//! F1, the plugin ([`Flamework`], DESIGN §10.7): ids and decorators.
//! - [`plugin`]: the `Plugin` / `PluginInstance` impls, [`FwFilePart`];
//! - [`setup`]: [`FwShared`] from the package, config, env and build infos, with the version check;
//! - [`metadata`]: JSDoc `@metadata` requests with `{@link}` entries;
//! - [`uid`]: type and declaration ids, late in `short` / `tiny` / `obfuscated` mode;
//! - [`class_hook`]: `Reflect.defineMetadata` at the static-block position, and the decorator checks;
//! - [`macros`]: user macros, as far as the `path` / `pathglob` intrinsics (the rest is F2+, declined);
//! - [`finish`]: id assignment in program order, `flamework.build`, the include JSON, the glob and path warnings;
//! - [`inputs`]: reading files and variables as recorded build inputs;
//! - [`part_codec`]: [`FwFilePart`] as bytes, for the compiler's incremental state.
//!
//! Clean builds only (incremental and watch: TODO(S2)).

